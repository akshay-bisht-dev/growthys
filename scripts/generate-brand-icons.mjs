// Builds the brand icon assets from Simple Icons (only the icons the site uses):
//   public/icons/brand-sprite.svg — one cached <symbol> sprite, referenced via <use>
//   src/data/brand-icons.js       — titles + brand colours (no path data)
// Keeping paths out of the HTML/RSC payload keeps pages light.
// Usage: npm run icons
import { mkdirSync, writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const SLUGS = [
  "html5",
  "css",
  "javascript",
  "php",
  "wordpress",
  "woocommerce",
  "shopify",
  "react",
  "nextdotjs",
  "nodedotjs",
  "express",
  "mongodb",
  "mongoose",
  "mysql",
  "postgresql",
  "python",
  "git",
  "github",
  "gitlab",
  "docker",
  "cloudflare",
  "linux",
  "figma",
  "gsap",
  "googleanalytics",
  "googleads",
  "meta",
  "vuedotjs",
  "tailwindcss",
  "redis",
  "nginx",
  "googletagmanager",
  "googlesearchconsole",
  "githubactions",
  "strapi",
  "sanity",
  "contentful",
  "openapiinitiative",
];

const out = {};
const symbols = [];
for (const slug of SLUGS) {
  const key = "si" + slug.charAt(0).toUpperCase() + slug.slice(1);
  const icon = icons[key];
  if (!icon) throw new Error(`Simple Icons has no "${slug}"`);
  out[slug] = { title: icon.title, hex: `#${icon.hex}` };
  symbols.push(`<symbol id="${slug}" viewBox="0 0 24 24"><path d="${icon.path}"/></symbol>`);
}

mkdirSync(new URL("../public/icons/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../public/icons/brand-sprite.svg", import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Simple Icons (CC0). Marks belong to their owners. -->${symbols.join("")}</svg>\n`,
);

const banner =
  "// Generated by scripts/generate-brand-icons.mjs from simple-icons (CC0).\n" +
  "// Brand marks remain the property of their respective owners.\n";
writeFileSync(
  new URL("../src/data/brand-icons.js", import.meta.url),
  `${banner}const brandIcons = ${JSON.stringify(out, null, 2)};\n\nexport default brandIcons;\n`,
);
console.log(`Wrote ${SLUGS.length} icons`);
